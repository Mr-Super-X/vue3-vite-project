/**
 * 基础格式校验工具（**纯前端格式校验**，不含业务规则）。
 *
 * 适用场景：
 * - 表单失焦/onChange 即时校验，给用户即时反馈
 * - 不替代后端权威校验：所有函数仅做正则匹配，业务规则（是否注册、是否唯一）由后端把关
 *
 * 与 `src/api/validator.ts` 的区别：
 * - 本文件：**字符串格式**校验（正则），无 IO、可同步
 * - `api/validator.ts`：**远程业务规则**校验（账号是否存在、token 是否过期），含网络 IO
 *
 * 约束与扩展：
 * - 中国大陆手机号仅校验 `1[3-9]\d{9}`，不支持国际号码、虚拟运营商细分（业务确认无此需求）
 * - 身份证支持 15 位旧版 + 18 位新版（GB 11643-1999），不做行政区划/出生日期合法性校验
 * - 邮箱不做 IDN（国际化域名）、不支持 `+` 邮箱别名（gmail 等允许的别名形式）
 *
 * @see [`api/validator.ts`](../api/validator.ts) 远程业务规则校验
 * @group 格式校验
 */

export const isEmail = (s: string): boolean => /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(s)

export const isPhone = (s: string): boolean => /^1[3-9]\d{9}$/.test(s)

/**
 * 校验中国大陆身份证号格式（GB 11643-1999）。
 *
 * **仅校验位数与末位字符**，不校验：
 * - 行政区划代码合法性（须查 GB/T 2260）
 * - 出生日期合法性（如 `999999` 不报错）
 * - 末位校验位是否匹配前 17 位（须按加权因子计算）
 *
 * 业务校验（实名认证、活体验证）由后端 + 第三方服务完成。
 *
 * @example
 * ```ts
 * isIdCard('110101199003078811') // true（18 位数字）
 * isIdCard('11010119900307881X') // true（18 位 + X 末位）
 * isIdCard('110101900307881')    // true（15 位旧版）
 * isIdCard('12345')              // false
 * ```
 *
 * @group 格式校验
 */
export const isIdCard = (s: string): boolean => /^\d{17}[\dXx]$/.test(s) || /^\d{15}$/.test(s)
